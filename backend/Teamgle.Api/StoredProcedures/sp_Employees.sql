-- =============================================================================
-- Description:  sp_GetAllRoles
--               Returns global roles (no company) and company-specific roles.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_GetAllRoles
    @companyId NVARCHAR(36)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT r.Roll_ID, r.Roll_name
    FROM   Roll r
    LEFT JOIN Roll_company rc ON r.Roll_ID = rc.roll_ID
    WHERE  rc.company_ID IS NULL OR rc.company_ID = @companyId
    ORDER BY r.Roll_name;
END;
GO


-- =============================================================================
-- Description:  sp_RoleNameExistsForCompany
--               Returns 1 if a role with the given name (case-insensitive)
--               already exists globally or for this company, 0 otherwise.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_RoleNameExistsForCompany
    @roleName  NVARCHAR(200),
    @companyId NVARCHAR(36)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT COUNT(*)
    FROM   Roll r
    LEFT JOIN Roll_company rc ON r.Roll_ID = rc.roll_ID
    WHERE  LOWER(r.Roll_name) = LOWER(@roleName)
      AND  (rc.company_ID IS NULL OR rc.company_ID = @companyId);
END;
GO


-- =============================================================================
-- Description:  sp_CreateRole
--               Inserts a new company-specific role into Roll and Roll_company.
--               The GUID is generated by the caller (C# repository).
--               Runs inside a transaction.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_CreateRole
    @rollId    NVARCHAR(36),
    @roleName  NVARCHAR(200),
    @companyId NVARCHAR(36)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRANSACTION;
    BEGIN TRY
        INSERT INTO Roll (Roll_ID, Roll_name)
        VALUES (@rollId, @roleName);

        INSERT INTO Roll_company (roll_ID, company_ID)
        VALUES (@rollId, @companyId);

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END;
GO


-- =============================================================================
-- Description:  sp_ValidateRoleIds
--               Accepts a comma-separated list of role IDs and returns the
--               count that are valid (global or belonging to this company).
--               C# compares the count against the expected number to validate.
--               Uses XML splitting (compatible with SQL Server 2008+).
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_ValidateRoleIds
    @roleIdsCsv NVARCHAR(MAX),
    @companyId  NVARCHAR(36)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT COUNT(*) AS MatchCount
    FROM   Roll r
    LEFT JOIN Roll_company rc ON r.Roll_ID = rc.roll_ID
    WHERE  r.Roll_ID IN (
        SELECT RTRIM(LTRIM(Split.a.value('.', 'NVARCHAR(36)')))
        FROM   (SELECT CAST('<X>' + REPLACE(@roleIdsCsv, ',', '</X><X>') + '</X>' AS XML)) AS A(xmlCol)
        CROSS APPLY A.xmlCol.nodes('/X') AS Split(a)
    )
    AND (rc.company_ID IS NULL OR rc.company_ID = @companyId);
END;
GO


-- =============================================================================
-- Description:  sp_EmailExists
--               Returns 1 if an email already exists in the User table, 0 otherwise.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_EmailExists
    @email NVARCHAR(200)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT COUNT(*)
    FROM   [User]
    WHERE  LOWER(email) = LOWER(@email);
END;
GO


-- =============================================================================
-- Description:  sp_GetEmployeesByCompany
--               Returns the core employee rows for a company (no roles).
--               Call sp_GetEmployeeRolesByCompany separately to load roles.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_GetEmployeesByCompany
    @companyId NVARCHAR(36)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT u.user_ID,
           u.firstName,
           u.lastName,
           u.email,
           u.phoneNum,
           u.FBUID,
           e.cost_per_hour
    FROM   [User] u
    INNER JOIN Employee e ON u.user_ID = e.user_ID
    WHERE  u.company_ID = @companyId
    ORDER BY u.firstName, u.lastName;
END;
GO


-- =============================================================================
-- Description:  sp_GetEmployeeRolesByCompany
--               Returns all role assignments for every employee in a company.
--               Used together with sp_GetEmployeesByCompany to build the list.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_GetEmployeeRolesByCompany
    @companyId NVARCHAR(36)
AS
BEGIN
    SET NOCOUNT ON;

    SELECT er.employee_user_ID,
           r.Roll_name
    FROM   Employee_Roll er
    INNER JOIN Roll r ON er.roll_ID = r.Roll_ID
    INNER JOIN [User] u ON er.employee_user_ID = u.user_ID
    WHERE  u.company_ID = @companyId;
END;
GO


-- =============================================================================
-- Description:  sp_GetEmployeeById
