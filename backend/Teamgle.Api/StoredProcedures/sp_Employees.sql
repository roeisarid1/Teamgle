-- =============================================================================
-- Description:  sp_CreateEmployee
--               Inserts a new User + Employee row and their role assignments
--               inside a single transaction.
--               Roles are passed as a comma-separated string (@roleIdsCsv).
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_CreateEmployee
    @userId      NVARCHAR(36),
    @email       NVARCHAR(200),
    @firstName   NVARCHAR(100),
    @lastName    NVARCHAR(100),
    @phoneNum    NVARCHAR(50)  = NULL,
    @costPerHour DECIMAL(18,2),
    @createdAt   DATETIME,
    @companyId   NVARCHAR(36),
    @roleIdsCsv  NVARCHAR(MAX) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRANSACTION;
    BEGIN TRY
        INSERT INTO [User]
            (user_ID, FBUID, email, firstName, lastName, phoneNum, company_ID, created_at)
        VALUES
            (@userId, NULL, @email, @firstName, @lastName, @phoneNum, @companyId, @createdAt);

        INSERT INTO Employee (user_ID, cost_per_hour, UID)
        VALUES (@userId, @costPerHour, NULL);

        IF @roleIdsCsv IS NOT NULL AND LEN(@roleIdsCsv) > 0
        BEGIN
            INSERT INTO Employee_Roll (employee_user_ID, roll_ID)
            SELECT @userId, RTRIM(LTRIM(Split.a.value('.', 'NVARCHAR(36)')))
            FROM   (SELECT CAST('<X>' + REPLACE(@roleIdsCsv, ',', '</X><X>') + '</X>' AS XML)) AS A(xmlCol)
            CROSS APPLY A.xmlCol.nodes('/X') AS Split(a);
        END

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END;
GO


-- =============================================================================
-- Description:  sp_UpdateEmployee
--               Updates User fields, Employee cost, and replaces all role
--               assignments in one transaction.
--               Raises state=2 (→ UnauthorizedAccessException) if employee
--               is not found or belongs to a different company.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_UpdateEmployee
    @userId      NVARCHAR(36),
    @companyId   NVARCHAR(36),
    @firstName   NVARCHAR(100),
    @lastName    NVARCHAR(100),
    @phoneNum    NVARCHAR(50)  = NULL,
    @costPerHour DECIMAL(18,2),
    @roleIdsCsv  NVARCHAR(MAX) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRANSACTION;
    BEGIN TRY
        IF NOT EXISTS (
            SELECT 1
            FROM   [User] u
            INNER JOIN Employee e ON u.user_ID = e.user_ID
            WHERE  u.user_ID = @userId AND u.company_ID = @companyId
        )
            RAISERROR('Employee not found or access denied.', 16, 2);

        UPDATE [User]
        SET    firstName = @firstName,
               lastName  = @lastName,
               phoneNum  = @phoneNum
        WHERE  user_ID = @userId;

        UPDATE Employee
        SET    cost_per_hour = @costPerHour
        WHERE  user_ID = @userId;

        DELETE FROM Employee_Roll
        WHERE  employee_user_ID = @userId;

        IF @roleIdsCsv IS NOT NULL AND LEN(@roleIdsCsv) > 0
        BEGIN
            INSERT INTO Employee_Roll (employee_user_ID, roll_ID)
            SELECT @userId, RTRIM(LTRIM(Split.a.value('.', 'NVARCHAR(36)')))
            FROM   (SELECT CAST('<X>' + REPLACE(@roleIdsCsv, ',', '</X><X>') + '</X>' AS XML)) AS A(xmlCol)
            CROSS APPLY A.xmlCol.nodes('/X') AS Split(a);
        END

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END;
GO


-- =============================================================================
-- Description:  sp_DeleteEmployee
--               Deletes Employee_Roll → Employee → User in a transaction.
--               Raises state=2 (→ UnauthorizedAccessException) if the employee
--               is not found or belongs to a different company.
-- =============================================================================
CREATE OR ALTER PROCEDURE sp_DeleteEmployee
    @userId    NVARCHAR(36),
    @companyId NVARCHAR(36)
AS
BEGIN
    SET NOCOUNT ON;

    BEGIN TRANSACTION;
    BEGIN TRY
        IF NOT EXISTS (
            SELECT 1
            FROM   [User] u
            INNER JOIN Employee e ON u.user_ID = e.user_ID
            WHERE  u.user_ID = @userId AND u.company_ID = @companyId
        )
            RAISERROR('Employee not found or access denied.', 16, 2);

        DELETE FROM Brief_Acknowledgment WHERE employee_user_ID = @userId;
        DELETE FROM Employee_Shift        WHERE employee_user_ID = @userId;
        DELETE FROM Employee_Roll         WHERE employee_user_ID = @userId;
        DELETE FROM Employee              WHERE user_ID          = @userId;
        DELETE FROM [User]
        WHERE  user_ID    = @userId
          AND  company_ID = @companyId;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END;
GO


